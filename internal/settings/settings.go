package settings

import (
	"crypto/rand"
	"encoding/base64"
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"sync"

	"docstorio/internal/fsutil"
)

// ErrInvalid reports a Patch value that is out of range (wrapped with the
// field name, e.g. "gamePort: must be 1-65535"). API: 400 bad_request.
var ErrInvalid = errors.New("invalid setting")

// fileMode is the mode of settings.json: it holds the factorio.com token and
// the RCON password.
const fileMode = 0600

// Settings is the content of manager/settings.json (file mode 0600). It is
// never sent to the API as is: View hides the token and the RCON password.
type Settings struct {
	Autostart        bool   `json:"autostart"`        // default true
	GamePort         int    `json:"gamePort"`         // default 34197 (UDP)
	WhitelistEnabled bool   `json:"whitelistEnabled"` // default false
	FactorioUsername string `json:"factorioUsername"` // factorio.com user; default ""
	FactorioToken    string `json:"factorioToken"`    // factorio.com token; default ""
	// RCONPassword is generated by Open when empty and passed to Factorio on
	// every launch.
	RCONPassword string `json:"rconPassword"`
}

// settingsKeys are the JSON keys of Settings; a file missing any of them is
// written back by Open with the defaults filled in.
var settingsKeys = []string{"autostart", "gamePort", "whitelistEnabled", "factorioUsername", "factorioToken", "rconPassword"}

// Defaults returns the settings used for a fresh data folder and for keys
// missing from an existing settings.json.
func Defaults() Settings {
	return Settings{Autostart: true, GamePort: 34197}
}

// View is the body of GET /api/settings.
type View struct {
	Autostart        bool   `json:"autostart"`
	GamePort         int    `json:"gamePort"`
	WhitelistEnabled bool   `json:"whitelistEnabled"`
	FactorioUsername string `json:"factorioUsername"`
	FactorioTokenSet bool   `json:"factorioTokenSet"`
}

// View returns the API view of s.
func (s Settings) View() View {
	return View{
		Autostart:        s.Autostart,
		GamePort:         s.GamePort,
		WhitelistEnabled: s.WhitelistEnabled,
		FactorioUsername: s.FactorioUsername,
		FactorioTokenSet: s.FactorioToken != "",
	}
}

// Patch is the body of PUT /api/settings. Nil fields are left unchanged.
// FactorioToken is write-only: "" clears it.
type Patch struct {
	Autostart        *bool   `json:"autostart"`
	GamePort         *int    `json:"gamePort"`
	WhitelistEnabled *bool   `json:"whitelistEnabled"`
	FactorioUsername *string `json:"factorioUsername"`
	FactorioToken    *string `json:"factorioToken"`
}

// Store holds the Settings in memory and writes settings.json on every
// change. All methods are safe for concurrent use; mu protects s and
// serialises the file writes.
type Store struct {
	mu    sync.Mutex
	paths Paths
	s     Settings
}

// Open loads settings.json (a missing file means Defaults(); missing keys
// take their default), generates RCONPassword if empty (random, URL-safe)
// and writes the file back (0600) if anything was filled in. A corrupt file
// is an error.
func Open(p Paths) (*Store, error) {
	path := p.SettingsFile()
	s := Defaults()
	dirty := false

	data, err := os.ReadFile(path)
	switch {
	case errors.Is(err, fs.ErrNotExist):
		dirty = true
	case err != nil:
		return nil, err
	default:
		var keys map[string]json.RawMessage
		if err := json.Unmarshal(data, &keys); err != nil {
			return nil, fmt.Errorf("%s: %w", path, err)
		}
		if err := json.Unmarshal(data, &s); err != nil {
			return nil, fmt.Errorf("%s: %w", path, err)
		}
		for _, k := range settingsKeys {
			if _, ok := keys[k]; !ok {
				dirty = true
			}
		}
	}

	if s.RCONPassword == "" {
		pw, err := newPassword()
		if err != nil {
			return nil, err
		}
		s.RCONPassword = pw
		dirty = true
	}

	st := &Store{paths: p, s: s}
	if dirty {
		if err := st.write(s); err != nil {
			return nil, err
		}
	}
	return st, nil
}

// Get returns a copy of the current settings.
func (st *Store) Get() Settings {
	st.mu.Lock()
	defer st.mu.Unlock()
	return st.s
}

// Apply validates and applies a Patch and writes settings.json.
// restartRequired is true when GamePort, WhitelistEnabled, FactorioUsername
// or FactorioToken actually changed (they reach Factorio only through its
// command line and the effective settings file, on the next start).
func (st *Store) Apply(p Patch) (s Settings, restartRequired bool, err error) {
	if p.GamePort != nil && (*p.GamePort < 1 || *p.GamePort > 65535) {
		return Settings{}, false, fmt.Errorf("gamePort: must be 1-65535: %w", ErrInvalid)
	}

	st.mu.Lock()
	defer st.mu.Unlock()

	old := st.s
	s = old
	if p.Autostart != nil {
		s.Autostart = *p.Autostart
	}
	if p.GamePort != nil {
		s.GamePort = *p.GamePort
	}
	if p.WhitelistEnabled != nil {
		s.WhitelistEnabled = *p.WhitelistEnabled
	}
	if p.FactorioUsername != nil {
		s.FactorioUsername = *p.FactorioUsername
	}
	if p.FactorioToken != nil {
		s.FactorioToken = *p.FactorioToken
	}

	if err := st.write(s); err != nil {
		return old, false, err
	}
	st.s = s
	restartRequired = s.GamePort != old.GamePort ||
		s.WhitelistEnabled != old.WhitelistEnabled ||
		s.FactorioUsername != old.FactorioUsername ||
		s.FactorioToken != old.FactorioToken
	return s, restartRequired, nil
}

// write stores s in settings.json (0600) via temp + rename.
func (st *Store) write(s Settings) error {
	data, err := json.MarshalIndent(s, "", "  ")
	if err != nil {
		return err
	}
	return fsutil.AtomicWrite(st.paths.SettingsFile(), append(data, '\n'), fileMode)
}

// newPassword returns a random URL-safe password (32 characters).
func newPassword() (string, error) {
	b := make([]byte, 24)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return base64.RawURLEncoding.EncodeToString(b), nil
}
